/**
 * Stages the WebAssembly payloads the app loads at runtime into public/, so
 * everything is served from our own origin — no CDN, no cross-origin isolation
 * headaches, and the app keeps working offline.
 *
 * Runs automatically before `next build` and `next dev`.
 */
import { copyFile, mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const publicDir = path.join(process.cwd(), "public");

/* ---- ffmpeg-core (~32 Mo) ---------------------------------------- */
{
  // "." resolves to dist/umd/ffmpeg-core.js under the CommonJS condition.
  const sourceDir = path.dirname(require.resolve("@ffmpeg/core"));
  const target = path.join(publicDir, "ffmpeg");
  await mkdir(target, { recursive: true });
  for (const file of ["ffmpeg-core.js", "ffmpeg-core.wasm"]) {
    const from = path.join(sourceDir, file);
    const to = path.join(target, file);
    const source = await stat(from);
    const existing = await stat(to).catch(() => null);
    if (existing && existing.size === source.size) continue;
    await copyFile(from, to);
    console.log(`ffmpeg-core → public/ffmpeg/${file} (${source.size} octets)`);
  }
}

/* ---- pdf.js worker ----------------------------------------------- */
{
  const from = path.join(
    path.dirname(require.resolve("pdfjs-dist/package.json")),
    "build",
    "pdf.worker.min.mjs",
  );
  const target = path.join(publicDir, "pdfjs");
  await mkdir(target, { recursive: true });
  const to = path.join(target, "pdf.worker.min.mjs");
  const source = await stat(from);
  const existing = await stat(to).catch(() => null);
  if (!existing || existing.size !== source.size) {
    await copyFile(from, to);
    console.log(`pdf.js → public/pdfjs/pdf.worker.min.mjs (${source.size} octets)`);
  }
}

/* ---- wawoff2 (Brotli / WOFF2) ------------------------------------ *
 * The Emscripten bindings are plain scripts that declare a global `Module`.
 * Wrapping each one in an IIFE keeps the two builds from colliding and lets
 * us load them on demand instead of through the bundler (which mistakes them
 * for Node.js code).
 */
{
  const sourceDir = path.join(
    path.dirname(require.resolve("wawoff2/index.js")),
    "build",
  );
  const target = path.join(publicDir, "wawoff2");
  await mkdir(target, { recursive: true });
  for (const [kind, file] of [
    ["compress", "compress_binding.js"],
    ["decompress", "decompress_binding.js"],
  ]) {
    const to = path.join(target, `${kind}.js`);
    const source = await readFile(path.join(sourceDir, file), "utf8");
    const wrapped = `/* wawoff2 ${kind} — generated by scripts/prepare-assets.mjs */\nwindow.__wawoff2_${kind} = (function () {\n${source}\nreturn Module;\n})();\n`;
    const existing = await readFile(to, "utf8").catch(() => null);
    if (existing === wrapped) continue;
    await writeFile(to, wrapped);
    console.log(`wawoff2 → public/wawoff2/${kind}.js (${wrapped.length} octets)`);
  }
}
